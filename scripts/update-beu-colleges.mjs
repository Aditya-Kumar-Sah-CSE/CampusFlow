async function main() {
  console.log(
    `\n🏫  Updating ${BEU_COLLEGES_DATA.length} BEU colleges with real online data...\n`
  );

  let updated = 0;
  let failed = 0;

  for (const col of BEU_COLLEGES_DATA) {
    const updatePayload = {
      name: col.name,
      website_url: col.website_url,
      logo_url: col.logo_url,
      address: col.address,
      contact_email: col.contact_email,
      contact_phone: col.contact_phone,
      established_year: col.established_year,
      tagline: col.tagline,
      affiliated_university: 'Bihar Engineering University, Patna',
      aicte_approved: true,
      updated_at: new Date().toISOString(),
    };

    const { data, error } = await supabase
      .from('colleges')
      .update(updatePayload)
      .eq('code', col.code)
      .select('id, name, code, slug, website_url, logo_url, affiliated_university');

    if (error) {
      console.error(`❌  Failed to update [${col.code}] ${col.name}:`, error.message);
      failed++;
    } else if (!data || data.length === 0) {
      console.warn(`⚠️  No row found for code ${col.code} (${col.name})`);
    } else {
      console.log(
        `✅  [${col.code}] ${col.name} -> ${col.website_url} | Affiliated: ${data[0].affiliated_university}`
      );
      updated++;
    }
  }

  console.log(`\n🎉  Finished: ${updated} updated, ${failed} failed.\n`);
}

main().catch((err) => {
  console.error('Fatal error:', err);
  process.exit(1);
});
